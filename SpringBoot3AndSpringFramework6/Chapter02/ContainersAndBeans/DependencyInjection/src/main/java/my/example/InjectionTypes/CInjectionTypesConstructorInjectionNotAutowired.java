package my.example.InjectionTypes;
//----------------------------------------------------------------------------------------------------------------------
import org.springframework.stereotype.Component;
//----------------------------------------------------------------------------------------------------------------------
@Component
public class CInjectionTypesConstructorInjectionNotAutowired
{
//----------------------------------------------------------------------------------------------------------------------
	private final CInjectionTypesBean							bean;
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	// !!!!! Ak ma TYPE iba jeden CONSTRUCTOR NEMUSI byt oznaceny pomocou ANNOTATION [@Autowired].
	public CInjectionTypesConstructorInjectionNotAutowired(CInjectionTypesBean bean)
	{
		this.bean=bean;
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public void Test()
	{
		String													Text=bean.Print();
		
		System.out.printf("CONSTRUCTOR INJECTION NOT AUTOWIRED - BEAN [%s].\n",Text);
	}	
//----------------------------------------------------------------------------------------------------------------------
}
