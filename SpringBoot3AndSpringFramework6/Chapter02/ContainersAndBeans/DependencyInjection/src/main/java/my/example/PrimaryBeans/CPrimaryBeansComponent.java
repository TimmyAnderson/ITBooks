package my.example.PrimaryBeans;
//----------------------------------------------------------------------------------------------------------------------
import org.springframework.stereotype.Component;
//----------------------------------------------------------------------------------------------------------------------
@Component
public class CPrimaryBeansComponent
{
//----------------------------------------------------------------------------------------------------------------------
	// !!!!! Obe BEANS budu namapovane na PRIMARY BEAN [CPrimaryBeansBean1].
	private final IPrimaryBeansInterface						bean1;
	private final IPrimaryBeansInterface						bean2;
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public CPrimaryBeansComponent(IPrimaryBeansInterface bean1, IPrimaryBeansInterface bean2)
	{
		this.bean1=bean1;
		this.bean2=bean2;
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public void Test()
	{
		String													myBeanText1=bean1.GetText();
		String													myBeanText2=bean2.GetText();
		
		System.out.printf("BEAN 1 [%s].\n",myBeanText1);
		System.out.printf("BEAN 2 [%s].\n",myBeanText2);
	}
//----------------------------------------------------------------------------------------------------------------------
}
//----------------------------------------------------------------------------------------------------------------------