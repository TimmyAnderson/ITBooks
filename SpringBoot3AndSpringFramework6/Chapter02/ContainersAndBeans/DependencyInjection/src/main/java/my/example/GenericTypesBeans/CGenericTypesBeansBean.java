package my.example.GenericTypesBeans;
//----------------------------------------------------------------------------------------------------------------------
public class CGenericTypesBeansBean<TType>
{
//----------------------------------------------------------------------------------------------------------------------
	private final String										id;
	private final TType											value;
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public CGenericTypesBeansBean(String id, TType value)
	{
		this.id=id;
		this.value=value;
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public String PrintValue()
	{
		String													text=String.format("ID [%s] VALUE [%s].",id,value);

		return(text);
	}
//----------------------------------------------------------------------------------------------------------------------
}
