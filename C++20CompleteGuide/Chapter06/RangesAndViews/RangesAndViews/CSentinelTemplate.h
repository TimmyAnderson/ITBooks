// !!!!! SENTINEL implementuje IBA OPERATOR [OPERATOR==], ale NIE OPERATOR [OPERATOR*], ako bezny ITERATOR, pretoze SENTINELS to nevyzaduju.
template<auto END>
class CSentinelTemplate final
{
//----------------------------------------------------------------------------------------------------------------------
	public:
		template<typename TIterator>
		bool operator==(TIterator Iterator) const;
//----------------------------------------------------------------------------------------------------------------------
};
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
template<auto END>
template<typename TIterator>
bool CSentinelTemplate<END>::operator==(TIterator Iterator) const
{
	// !!! SENTINEL kontroluje ci ITERATOR ukazuje na END VALUE.
	if (*Iterator==END)
	{
		return(true);
	}
	else
	{
		return(false);
	}
}
