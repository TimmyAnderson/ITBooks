//----------------------------------------------------------------------------------------------------------------------
#pragma once
//----------------------------------------------------------------------------------------------------------------------
#include <vector>
#include <iostream>
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
template<typename TItem>
class CRangeVector final
{
//----------------------------------------------------------------------------------------------------------------------
	private:
		std::vector<TItem>										MCollection;

	public:
		std::vector<TItem>::const_iterator begin(void) const;
		std::vector<TItem>::const_iterator end(void) const;

	public:
		CRangeVector(std::initializer_list<TItem> Values);
		~CRangeVector(void);
//----------------------------------------------------------------------------------------------------------------------
};
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
template<typename TItem>
CRangeVector<TItem>::CRangeVector(std::initializer_list<TItem> Values)
	: MCollection(Values)
{
}
//----------------------------------------------------------------------------------------------------------------------
template<typename TItem>
CRangeVector<TItem>::~CRangeVector(void)
{
}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
template<typename TItem>
std::vector<TItem>::const_iterator CRangeVector<TItem>::begin(void) const
{
	std::wcout << L"BEGIN ITERATOR CALLED." << std::endl;

	typename std::vector<TItem>::const_iterator					Iterator=MCollection.begin();

	return(Iterator);
}
//----------------------------------------------------------------------------------------------------------------------
template<typename TItem>
std::vector<TItem>::const_iterator CRangeVector<TItem>::end(void) const
{
	std::wcout << L"END ITERATOR CALLED." << std::endl;

	typename std::vector<TItem>::const_iterator					Iterator=MCollection.end();

	return(Iterator);
}
//----------------------------------------------------------------------------------------------------------------------