package my.example.GenericTypesBeans;
//----------------------------------------------------------------------------------------------------------------------
import java.util.UUID;

import org.springframework.stereotype.Component;
//----------------------------------------------------------------------------------------------------------------------
// !!!!! SPRING FRAMEWORK vytvori VZDY iba 1 INSTANCIU GENERIC TYPE SPRING MANAGED BEAN. To znamena, ze GENERIC TYPE SPRING MANAGED BEANS MUSIA byt VZDY vytvarane pomocou FACTORY METHODS.
@Component
public class CGenericTypesBeansComponent2<TType>
{
//----------------------------------------------------------------------------------------------------------------------
	private String												id;
	private TType												value;
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public CGenericTypesBeansComponent2()
	{
		id=UUID.randomUUID().toString();
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	// !!!!! Ak je VALUE nastavena cez bezny (NON BEAN) SETTER, GENERIC BEAN funguje korektne.
	public void setValue(TType value)
	{
		this.value=value;
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public String Print()
	{
		String													text=String.format("COMPONENT 2 - ID [%s] VALUE [%s].",id,value);

		return(text);
	}
//----------------------------------------------------------------------------------------------------------------------
}
//----------------------------------------------------------------------------------------------------------------------