package my.example.LazyBeans;
//----------------------------------------------------------------------------------------------------------------------
import org.springframework.context.annotation.Lazy;

import org.springframework.stereotype.Component;
//----------------------------------------------------------------------------------------------------------------------
// !!! BEAN je nacitany ako LAZY BEAN.
@Lazy(true)
@Component
public class CLazyBeansBean2
{
//----------------------------------------------------------------------------------------------------------------------
	public CLazyBeansBean2()
	{
		System.out.printf("!!!!! BEAN 2 CREATED.\n");
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public String GetText()
	{
		return("From BEAN 2 - LAZY BEAN.");
	}
//----------------------------------------------------------------------------------------------------------------------
}
