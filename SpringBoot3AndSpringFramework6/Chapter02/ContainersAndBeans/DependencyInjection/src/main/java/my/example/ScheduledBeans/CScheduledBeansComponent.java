package my.example.ScheduledBeans;
//----------------------------------------------------------------------------------------------------------------------
import org.springframework.beans.factory.annotation.Autowired;

import org.springframework.stereotype.Component;
//----------------------------------------------------------------------------------------------------------------------
@Component
public class CScheduledBeansComponent
{
//----------------------------------------------------------------------------------------------------------------------
	private final CScheduledBeansBean							bean;
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	@Autowired
	public CScheduledBeansComponent(CScheduledBeansBean bean)
	{
		this.bean=bean;
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public void Test()
	{
		try
		{
			bean.MyScheduledMethod();
			
			Thread.sleep(10000);
			
			bean.MyScheduledMethod();
		}
		catch (InterruptedException e)
		{
			System.out.printf("EXCEPTION [%s].\n",e.getMessage());
		}
	}
//----------------------------------------------------------------------------------------------------------------------
}
//----------------------------------------------------------------------------------------------------------------------