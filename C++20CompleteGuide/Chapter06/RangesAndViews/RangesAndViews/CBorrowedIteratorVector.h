//----------------------------------------------------------------------------------------------------------------------
#pragma once
//----------------------------------------------------------------------------------------------------------------------
#include <vector>
#include <iostream>
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
template<typename TItem>
class CBorrowedIteratorVector final
{
//----------------------------------------------------------------------------------------------------------------------
	private:
		std::vector<TItem>										MCollection;

	public:
		std::vector<TItem>::const_iterator begin(void) const;
		std::vector<TItem>::const_iterator end(void) const;

	public:
		CBorrowedIteratorVector(std::initializer_list<TItem> Values);
		~CBorrowedIteratorVector(void);
//----------------------------------------------------------------------------------------------------------------------
};
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
template<typename TItem>
CBorrowedIteratorVector<TItem>::CBorrowedIteratorVector(std::initializer_list<TItem> Values)
	: MCollection(Values)
{
	std::wcout << L"CONSTRUCTOR CALLED." << std::endl;
}
//----------------------------------------------------------------------------------------------------------------------
template<typename TItem>
CBorrowedIteratorVector<TItem>::~CBorrowedIteratorVector(void)
{
	std::wcout << L"DESTRUCTOR CALLED." << std::endl;
}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
template<typename TItem>
std::vector<TItem>::const_iterator CBorrowedIteratorVector<TItem>::begin(void) const
{
	typename std::vector<TItem>::const_iterator					Iterator=MCollection.begin();

	return(Iterator);
}
//----------------------------------------------------------------------------------------------------------------------
template<typename TItem>
std::vector<TItem>::const_iterator CBorrowedIteratorVector<TItem>::end(void) const
{
	typename std::vector<TItem>::const_iterator					Iterator=MCollection.end();

	return(Iterator);
}
