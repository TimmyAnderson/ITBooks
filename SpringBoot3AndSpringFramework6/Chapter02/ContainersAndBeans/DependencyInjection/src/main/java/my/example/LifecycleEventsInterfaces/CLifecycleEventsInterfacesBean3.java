package my.example.LifecycleEventsInterfaces;
//----------------------------------------------------------------------------------------------------------------------
import org.springframework.beans.factory.DisposableBean;
import org.springframework.beans.factory.InitializingBean;

import org.springframework.stereotype.Component;

import jakarta.annotation.PostConstruct;
import jakarta.annotation.PreDestroy;
//----------------------------------------------------------------------------------------------------------------------
@Component
public class CLifecycleEventsInterfacesBean3 implements InitializingBean, DisposableBean
{
//----------------------------------------------------------------------------------------------------------------------
	public CLifecycleEventsInterfacesBean3()
	{
		System.out.printf("!!!!! BEAN 3 CREATED.\n");
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	@Override
	public void afterPropertiesSet() throws Exception
	{
		System.out.printf("!!!!! BEAN 3 - AFTER PROPERTIES SET CALLED.\n");
	}
//----------------------------------------------------------------------------------------------------------------------
	@Override
	public void destroy() throws Exception
	{
		System.out.printf("!!!!! BEAN 3 - DESTROY CALLED.\n");
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	// !!! LIFECYCLE CALLBACK implementovany pomocou ANNOTATION.
	@PostConstruct
	private void MyPostConstructMethod()
	{
		System.out.printf("!!!!! BEAN 3 - POST CONSTRUCT CALLED.\n");
	}
//----------------------------------------------------------------------------------------------------------------------
	// !!! LIFECYCLE CALLBACK implementovany pomocou ANNOTATION.
	@PreDestroy
	private void MyPreDestroyMethod()
	{
		System.out.printf("!!!!! BEAN 3 - PRE DESTROY CALLED.\n");
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public String GetText()
	{
		return("From BEAN 3.");
	}
//----------------------------------------------------------------------------------------------------------------------
}
//----------------------------------------------------------------------------------------------------------------------