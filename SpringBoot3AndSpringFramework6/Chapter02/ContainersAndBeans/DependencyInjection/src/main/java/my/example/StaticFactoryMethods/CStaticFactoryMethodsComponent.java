package my.example.StaticFactoryMethods;
//----------------------------------------------------------------------------------------------------------------------
import org.springframework.beans.factory.annotation.Autowired;

import org.springframework.stereotype.Component;
//----------------------------------------------------------------------------------------------------------------------
@Component
public class CStaticFactoryMethodsComponent
{
//----------------------------------------------------------------------------------------------------------------------
	private final CStaticFactoryMethodsBean						bean;
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	@Autowired
	public CStaticFactoryMethodsComponent(CStaticFactoryMethodsBean bean)
	{
		this.bean=bean;
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public void Test()
	{
		String													text=bean.Print();
		
		System.out.printf("BEAN - VALUE [%s].\n",text);
	}
//----------------------------------------------------------------------------------------------------------------------
}
