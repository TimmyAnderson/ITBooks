package my.example.LifecycleEventsAnnotations;
//----------------------------------------------------------------------------------------------------------------------
import org.springframework.stereotype.Component;

import jakarta.annotation.PostConstruct;
import jakarta.annotation.PreDestroy;
//----------------------------------------------------------------------------------------------------------------------
@Component
public class CLifecycleEventsAnnotationsBean1
{
//----------------------------------------------------------------------------------------------------------------------
	public CLifecycleEventsAnnotationsBean1()
	{
		System.out.printf("!!!!! BEAN 1 CREATED.\n");
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	@PostConstruct
	private void MyPostConstructMethod()
	{
		System.out.printf("!!!!! BEAN 1 - POST CONSTRUCT CALLED.\n");
	}
//----------------------------------------------------------------------------------------------------------------------
	@PreDestroy
	private void MyPreDestroyMethod()
	{
		System.out.printf("!!!!! BEAN 1 - PRE DESTROY CALLED.\n");
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public String GetText()
	{
		return("From BEAN 1.");
	}
//----------------------------------------------------------------------------------------------------------------------
}
//----------------------------------------------------------------------------------------------------------------------