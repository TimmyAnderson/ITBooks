package my.example.MissingBeans;
//----------------------------------------------------------------------------------------------------------------------
import org.springframework.beans.factory.annotation.Autowired;

import org.springframework.stereotype.Component;
//----------------------------------------------------------------------------------------------------------------------
@Component
public class CMissingBeansComponent
{
//----------------------------------------------------------------------------------------------------------------------
	private final CMissingBeansBean								bean;
	// !!!!! CLASS NIE JE BEAN.
	private final CMissingBeansNotBean							notBean;
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	@Autowired
	public CMissingBeansComponent(CMissingBeansBean bean, CMissingBeansNotBean notBean)
	{
		this.bean=bean;
		this.notBean=notBean;
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public void Test()
	{
		String													TextBean=bean.Print();
		String													TextNotBean=notBean.Print();
		
		System.out.printf("MISSING BEANS - BEAN [%s].\n",TextBean);
		System.out.printf("MISSING BEANS - NOT BEAN [%s].\n",TextNotBean);
	}	
//----------------------------------------------------------------------------------------------------------------------
}
