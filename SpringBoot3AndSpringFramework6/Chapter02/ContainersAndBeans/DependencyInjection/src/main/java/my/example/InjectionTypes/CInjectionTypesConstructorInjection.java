package my.example.InjectionTypes;
//----------------------------------------------------------------------------------------------------------------------
import org.springframework.beans.factory.annotation.Autowired;

import org.springframework.stereotype.Component;
//----------------------------------------------------------------------------------------------------------------------
@Component
public class CInjectionTypesConstructorInjection
{
//----------------------------------------------------------------------------------------------------------------------
	private final CInjectionTypesBean							bean;
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public CInjectionTypesConstructorInjection()
	{
		System.out.println("DEFAULT CONSTRUCTOR CALLED.");
		
		this.bean=new CInjectionTypesBean();
	}
//----------------------------------------------------------------------------------------------------------------------
	// !!! Ak ma TYPE viacero CONSTRUCTORS, jeden CONSTRUCTOR MUSI byt oznaceny pomocou ANNOTATION [@Autowired].
	@Autowired
	public CInjectionTypesConstructorInjection(CInjectionTypesBean bean)
	{
		System.out.println("NON-DEFAULT CONSTRUCTOR CALLED.");
		
		this.bean=bean;
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public void Test()
	{
		String													Text=bean.Print();
		
		System.out.printf("CONSTRUCTOR INJECTION - BEAN [%s].\n",Text);
	}	
//----------------------------------------------------------------------------------------------------------------------
}
//----------------------------------------------------------------------------------------------------------------------