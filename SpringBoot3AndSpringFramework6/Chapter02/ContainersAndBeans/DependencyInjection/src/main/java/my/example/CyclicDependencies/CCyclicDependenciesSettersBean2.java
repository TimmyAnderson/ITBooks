package my.example.CyclicDependencies;
//----------------------------------------------------------------------------------------------------------------------
import org.springframework.beans.factory.annotation.Autowired;

import org.springframework.stereotype.Component;
//----------------------------------------------------------------------------------------------------------------------
@Component
public class CCyclicDependenciesSettersBean2
{
//----------------------------------------------------------------------------------------------------------------------
	private CCyclicDependenciesSettersBean1						bean;
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	// !!!!! SETTER umoznuje riesit CYLIC DEPENDENCIES.
	@Autowired
	private void MySetter(CCyclicDependenciesSettersBean1 bean)
	{
		this.bean=bean;
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public String FromBean()
	{
		return("This is from BEAN 2.");
	}
//----------------------------------------------------------------------------------------------------------------------
	public String Print()
	{
		String													fromBean=bean.FromBean();
		String													returnValue=String.format("This is BEAN. FROM BEAN 1 [%s].",fromBean);
		
		return(returnValue);
	}
//----------------------------------------------------------------------------------------------------------------------
}
//----------------------------------------------------------------------------------------------------------------------