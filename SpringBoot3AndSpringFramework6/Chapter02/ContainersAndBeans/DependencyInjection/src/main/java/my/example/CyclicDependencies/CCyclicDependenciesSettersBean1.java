package my.example.CyclicDependencies;
//----------------------------------------------------------------------------------------------------------------------
import org.springframework.beans.factory.annotation.Autowired;

import org.springframework.stereotype.Component;
//----------------------------------------------------------------------------------------------------------------------
@Component
public class CCyclicDependenciesSettersBean1
{
//----------------------------------------------------------------------------------------------------------------------
	private CCyclicDependenciesSettersBean2						bean;
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	// !!!!! SETTER umoznuje riesit CYLIC DEPENDENCIES.
	@Autowired
	private void MySetter(CCyclicDependenciesSettersBean2 bean)
	{
		this.bean=bean;
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public String FromBean()
	{
		return("This is from BEAN 1.");
	}
//----------------------------------------------------------------------------------------------------------------------
	public String Print()
	{
		String													fromBean=bean.FromBean();
		String													returnValue=String.format("This is BEAN. FROM BEAN 2 [%s].",fromBean);
		
		return(returnValue);
	}
//----------------------------------------------------------------------------------------------------------------------
}
//----------------------------------------------------------------------------------------------------------------------