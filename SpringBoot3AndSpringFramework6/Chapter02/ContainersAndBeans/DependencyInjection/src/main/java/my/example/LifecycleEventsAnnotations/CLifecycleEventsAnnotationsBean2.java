package my.example.LifecycleEventsAnnotations;
//----------------------------------------------------------------------------------------------------------------------
import org.springframework.stereotype.Component;

import jakarta.annotation.PostConstruct;
import jakarta.annotation.PreDestroy;
//----------------------------------------------------------------------------------------------------------------------
@Component
public class CLifecycleEventsAnnotationsBean2
{
//----------------------------------------------------------------------------------------------------------------------
	public CLifecycleEventsAnnotationsBean2()
	{
		System.out.printf("!!!!! BEAN 2 CREATED.\n");
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	@PostConstruct
	private void MyPostConstructMethod()
	{
		System.out.printf("!!!!! BEAN 2 - POST CONSTRUCT CALLED.\n");
	}
//----------------------------------------------------------------------------------------------------------------------
	@PreDestroy
	private void MyPreDestroyMethod()
	{
		System.out.printf("!!!!! BEAN 2 - PRE DESTROY CALLED.\n");
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public String GetText()
	{
		return("From BEAN 2.");
	}
//----------------------------------------------------------------------------------------------------------------------
}
//----------------------------------------------------------------------------------------------------------------------