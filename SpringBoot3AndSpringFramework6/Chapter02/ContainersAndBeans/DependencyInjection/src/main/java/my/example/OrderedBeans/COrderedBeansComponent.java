package my.example.OrderedBeans;
//----------------------------------------------------------------------------------------------------------------------
import java.util.List;

import org.springframework.stereotype.Component;
//----------------------------------------------------------------------------------------------------------------------
@Component
public class COrderedBeansComponent
{
//----------------------------------------------------------------------------------------------------------------------
	private final List<IOrderedBeansInterface>					beans;
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public COrderedBeansComponent(List<IOrderedBeansInterface> beans)
	{
		this.beans=beans;
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public void Test()
	{
		for(int index=0;index<beans.size();index++)
		{
			IOrderedBeansInterface								bean=beans.get(index);
			String												beanText=bean.GetText();
			
			System.out.printf("BEAN [%d] - VALUE [%s].\n",(index+1),beanText);
		}
	}
//----------------------------------------------------------------------------------------------------------------------
}
