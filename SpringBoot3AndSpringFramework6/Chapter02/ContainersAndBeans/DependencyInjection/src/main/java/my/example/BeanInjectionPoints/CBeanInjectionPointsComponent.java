package my.example.BeanInjectionPoints;
//----------------------------------------------------------------------------------------------------------------------
import org.springframework.beans.factory.annotation.Autowired;

import org.springframework.stereotype.Component;
//----------------------------------------------------------------------------------------------------------------------
@Component
public class CBeanInjectionPointsComponent
{
//----------------------------------------------------------------------------------------------------------------------
	private final CBeanInjectionPointsBean						bean1;
//----------------------------------------------------------------------------------------------------------------------
	private CBeanInjectionPointsBean							bean2;
//----------------------------------------------------------------------------------------------------------------------
	@Autowired
	private CBeanInjectionPointsBean							bean3;
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	@Autowired
	public CBeanInjectionPointsComponent(CBeanInjectionPointsBean bean1)
	{
		this.bean1=bean1;
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	@Autowired
	public void MySetter(CBeanInjectionPointsBean bean2)
	{
		this.bean2=bean2;
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public void Test()
	{
		String													valueBean1=bean1.getValue();
		String													valueBean2=bean2.getValue();
		String													valueBean3=bean3.getValue();

		System.out.printf("BEAN 1 - VALUE [%s].\n",valueBean1);
		System.out.printf("BEAN 2 - VALUE [%s].\n",valueBean2);
		System.out.printf("BEAN 3 - VALUE [%s].\n",valueBean3);
	}
//----------------------------------------------------------------------------------------------------------------------
}
//----------------------------------------------------------------------------------------------------------------------