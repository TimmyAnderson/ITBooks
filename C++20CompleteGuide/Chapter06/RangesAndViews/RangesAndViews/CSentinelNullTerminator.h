// !!!!! SENTINEL implementuje IBA OPERATOR [OPERATOR==], ale NIE OPERATOR [OPERATOR*], ako bezny ITERATOR, pretoze SENTINELS to nevyzaduju.
class CSentinelNullTerminator final
{
//----------------------------------------------------------------------------------------------------------------------
	public:
		template<typename TIterator>
		bool operator==(TIterator Iterator) const;
//----------------------------------------------------------------------------------------------------------------------
};
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
template<typename TIterator>
bool CSentinelNullTerminator::operator==(TIterator Iterator) const
{
	// !!! SENTINEL kontroluje ci ITERATOR ukazuje na CHARACTER [\0].
	if (*Iterator==L'\0')
	{
		return(true);
	}
	else
	{
		return(false);
	}
}
