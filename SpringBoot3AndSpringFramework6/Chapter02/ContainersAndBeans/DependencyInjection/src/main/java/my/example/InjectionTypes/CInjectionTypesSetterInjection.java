package my.example.InjectionTypes;
//----------------------------------------------------------------------------------------------------------------------
import org.springframework.beans.factory.annotation.Autowired;

import org.springframework.stereotype.Component;
//----------------------------------------------------------------------------------------------------------------------
@Component
public class CInjectionTypesSetterInjection
{
//----------------------------------------------------------------------------------------------------------------------
	private CInjectionTypesBean									bean;
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	// !!! SETTER MUSI byt oznaceny pomocou ANNOTATION [@Autowired].
	// !!! SETTER NEMUSI mat PREFIX [set].
	@Autowired
	public void MySetter(CInjectionTypesBean bean)
	{
		this.bean=bean;
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public void Test()
	{
		String													Text=bean.Print();
		
		System.out.printf("SETTER INJECTION - BEAN [%s].\n",Text);
	}	
//----------------------------------------------------------------------------------------------------------------------
}
