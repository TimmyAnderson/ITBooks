package my.example.CyclicDependencies;
//----------------------------------------------------------------------------------------------------------------------
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.context.annotation.Lazy;
import org.springframework.stereotype.Component;
//----------------------------------------------------------------------------------------------------------------------
// !!!!! ANNOTATION [@Lazy] riesi CYCLIC DEPENDENCY.
@Lazy
@Component
public class CCyclicDependenciesLazyBean2
{
//----------------------------------------------------------------------------------------------------------------------
	private final CCyclicDependenciesLazyBean1					bean;
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	@Autowired
	private CCyclicDependenciesLazyBean2(CCyclicDependenciesLazyBean1 bean)
	{
		this.bean=bean;
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public String FromBean()
	{
		return("This is from BEAN 1.");
	}
//----------------------------------------------------------------------------------------------------------------------
	public String Print()
	{
		String													fromBean=bean.FromBean();
		String													returnValue=String.format("This is BEAN. FROM BEAN 2 [%s].",fromBean);
		
		return(returnValue);
	}
//----------------------------------------------------------------------------------------------------------------------
}
//----------------------------------------------------------------------------------------------------------------------