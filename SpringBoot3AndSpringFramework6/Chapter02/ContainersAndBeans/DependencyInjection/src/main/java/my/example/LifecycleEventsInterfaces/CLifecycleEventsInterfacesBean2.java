package my.example.LifecycleEventsInterfaces;
//----------------------------------------------------------------------------------------------------------------------
import org.springframework.beans.factory.DisposableBean;
import org.springframework.beans.factory.InitializingBean;
//----------------------------------------------------------------------------------------------------------------------
public class CLifecycleEventsInterfacesBean2 implements InitializingBean, DisposableBean
{
//----------------------------------------------------------------------------------------------------------------------
	public CLifecycleEventsInterfacesBean2()
	{
		System.out.printf("!!!!! BEAN 2 CREATED.\n");
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	@Override
	public void afterPropertiesSet() throws Exception
	{
		System.out.printf("!!!!! BEAN 2 - AFTER PROPERTIES SET CALLED.\n");
	}
//----------------------------------------------------------------------------------------------------------------------
	@Override
	public void destroy() throws Exception
	{
		System.out.printf("!!!!! BEAN 2 - DESTROY CALLED.\n");
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public String GetText()
	{
		return("From BEAN 2.");
	}
//----------------------------------------------------------------------------------------------------------------------
}
//----------------------------------------------------------------------------------------------------------------------