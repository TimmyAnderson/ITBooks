package my.example.LazyBeans;
//----------------------------------------------------------------------------------------------------------------------
import org.springframework.context.annotation.Lazy;

import org.springframework.stereotype.Component;
//----------------------------------------------------------------------------------------------------------------------
// !!! BEAN je nacitany ako EAGER BEAN.
@Lazy(false)
@Component
public class CLazyBeansBean1
{
//----------------------------------------------------------------------------------------------------------------------
	public CLazyBeansBean1()
	{
		System.out.printf("!!!!! BEAN 1 CREATED.\n");
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public String GetText()
	{
		return("From BEAN 1 - EAGER BEAN.");
	}
//----------------------------------------------------------------------------------------------------------------------
}
