package my.example.LifecycleEventsInterfaces;
//----------------------------------------------------------------------------------------------------------------------
import org.springframework.beans.factory.DisposableBean;
import org.springframework.beans.factory.InitializingBean;

import org.springframework.stereotype.Component;
//----------------------------------------------------------------------------------------------------------------------
@Component
public class CLifecycleEventsInterfacesBean1 implements InitializingBean, DisposableBean
{
//----------------------------------------------------------------------------------------------------------------------
	public CLifecycleEventsInterfacesBean1()
	{
		System.out.printf("!!!!! BEAN 1 CREATED.\n");
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	@Override
	public void afterPropertiesSet() throws Exception
	{
		System.out.printf("!!!!! BEAN 1 - AFTER PROPERTIES SET CALLED.\n");
	}
//----------------------------------------------------------------------------------------------------------------------
	@Override
	public void destroy() throws Exception
	{
		System.out.printf("!!!!! BEAN 1 - DESTROY CALLED.\n");
	}
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------
	public String GetText()
	{
		return("From BEAN 1.");
	}
//----------------------------------------------------------------------------------------------------------------------
}
//----------------------------------------------------------------------------------------------------------------------